#!/usr/bin/env python3
"""Assemble the browser app in web/ (run with the project venv).

  .venv/bin/python tools/build_web.py            # sources, assets, samples, Pyodide runtime
  .venv/bin/python tools/build_web.py --no-samples
  python3 tools/build_web.py --site _site       # static site for GitHub Pages (stdlib only)

The app runs the unchanged skewcal Python package in the browser through
Pyodide, so the runtime and its wheels are copied next to the page (hosts like
claude.ai Artifacts only allow same-origin fetches). Generated files:

  web/py_bundle.js        Python sources as one JS object
  web/assets/             plate STL, reference-sheet PDFs, skew_gcode.py
  web/samples/            two example scan pairs (before / after correction)
  web/sample_result.json  precomputed result for the first sample, shown at load
  web/pyodide/            Pyodide runtime + numpy, opencv-python, pillow, scipy

--site writes a standalone static site without the Pyodide copy (the worker then
loads Pyodide from the jsDelivr CDN) and wraps index.html in a full HTML document.
Samples are not regenerated in that mode: web/samples/ is committed.
"""
import argparse
import hashlib
import json
import os
import shutil
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "web")
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(WEB, "py"))

PYODIDE = "0.27.7"
PYODIDE_URL = f"https://cdn.jsdelivr.net/pyodide/v{PYODIDE}/full/"
RUNTIME = ["pyodide.js", "pyodide.asm.js", "pyodide.asm.wasm", "python_stdlib.zip", "pyodide-lock.json"]
PACKAGES = ["numpy", "opencv-python", "pillow", "scipy", "openblas"]

PY_SOURCES = {
    "skewcal/__init__.py": "skewcal/__init__.py",
    "skewcal/analyze.py": "skewcal/analyze.py",
    "skewcal/plate.py": "skewcal/plate.py",
    "skewcal/sheet.py": "skewcal/sheet.py",
    "skewcal_cli.py": "skewcal.py",
    "skew_gcode.py": "skew_gcode.py",
    "bridge.py": "web/py/bridge.py",
}

# name, title, scan files (relative to runs/), note
SAMPLES = [
    ("before", "Prusa MINI+, before correction",
     ["scan_2026-10-13/IMG_20261013_0008.tif", "scan_2026-10-13/IMG_20261013_0009.tif"]),
    ("after", "Prusa MINI+, after correction",
     ["scan_2026-10-13_corrected/IMG_20261013_0010.tif", "scan_2026-10-13_corrected/IMG_20261013_0011.tif"]),
]
SAMPLE_DPI = 400

# index.html is written as an Artifact page body; hosts outside claude.ai need this skeleton
SKELETON = ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
            '<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);'
            'padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui,sans-serif}'
            'img{max-width:100%}[hidden]{display:none!important}</style></head><body>')


def wrapped_index():
    with open(os.path.join(WEB, "index.html")) as f:
        return SKELETON + f.read() + "</body></html>\n"


def write_site(out):
    out = os.path.abspath(out)
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    for name in ["app.js", "worker.js", "py_bundle.js", "sample_result.json", "screen_markers.json"]:
        shutil.copy2(os.path.join(WEB, name), out)
    for d in ["samples", "assets"]:
        shutil.copytree(os.path.join(WEB, d), os.path.join(out, d))
    with open(os.path.join(out, "index.html"), "w") as f:
        f.write(wrapped_index())
    open(os.path.join(out, ".nojekyll"), "w").close()
    size = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(out) for f in fs)
    print(f"site written to {out} ({size / 1e6:.1f} MB)")


def bundle_python():
    files = {}
    for dst, src in PY_SOURCES.items():
        with open(os.path.join(ROOT, src)) as f:
            files[dst] = f.read()
    with open(os.path.join(WEB, "py_bundle.js"), "w") as f:
        f.write("// Generated by tools/build_web.py - do not edit.\n")
        f.write("self.SKEWCAL_PY = " + json.dumps(files) + ";\n")
    print(f"py_bundle.js: {len(files)} files")


def copy_assets():
    out = os.path.join(WEB, "assets")
    os.makedirs(out, exist_ok=True)
    for name in ["skewcal_plate.stl", "skewcal_plate.json", "skewcal_plate_standard.stl",
                 "skewcal_plate_standard.json", "skew_gcode.py",
                 "skewcal_reference_letter.pdf", "skewcal_reference_letter_dark.pdf",
                 "skewcal_reference_a4.pdf", "skewcal_reference_a4_dark.pdf"]:
        shutil.copy2(os.path.join(ROOT, name), out)
    # Artifact downloads only allow common extensions, so STL and .py ship zipped too
    import zipfile
    for zname, members in [("skewcal_plate.zip", ["skewcal_plate.stl", "skewcal_plate.json"]),
                           ("skewcal_plate_standard.zip", ["skewcal_plate_standard.stl", "skewcal_plate_standard.json"]),
                           ("skew_gcode.zip", ["skew_gcode.py"])]:
        with zipfile.ZipFile(os.path.join(out, zname), "w", zipfile.ZIP_DEFLATED) as z:
            for m in members:
                z.write(os.path.join(ROOT, m), m)
    print("assets copied")


def export_screen_markers():
    """Bit patterns of the tablet-screen reference markers, drawn by the web app."""
    import cv2
    from skewcal import sheet
    dic = cv2.aruco.getPredefinedDictionary(sheet.ARUCO_DICT)
    markers = []
    for mid, x, y in sheet.marker_layout("screen"):
        img = cv2.aruco.generateImageMarker(dic, mid, 6, borderBits=1) > 0      # True = white
        markers.append(dict(id=mid, x=x, y=y, bits=["".join("1" if v else "0" for v in row) for row in img]))
    out = dict(marker_mm=sheet.SCREEN_MARKER_SIZE, window_half_mm=sheet.SCREEN_WINDOW_HALF,
               ring_mm=sheet.SCREEN_RING, glass_mm=sheet.SCREEN_GLASS_MM, markers=markers)
    with open(os.path.join(WEB, "screen_markers.json"), "w") as f:
        json.dump(out, f)
    print(f"screen_markers.json: {len(markers)} markers")


def fetch_pyodide():
    out = os.path.join(WEB, "pyodide")
    os.makedirs(out, exist_ok=True)

    def get(name, sha=None):
        path = os.path.join(out, name)
        if not os.path.exists(path):
            print("  downloading", name)
            urllib.request.urlretrieve(PYODIDE_URL + name, path)
        if sha:
            with open(path, "rb") as f:
                if hashlib.sha256(f.read()).hexdigest() != sha:
                    os.remove(path)
                    sys.exit(f"checksum mismatch for {name}")

    for name in RUNTIME:
        get(name)
    lock = json.load(open(os.path.join(out, "pyodide-lock.json")))
    for pkg in PACKAGES:
        info = lock["packages"][pkg]
        get(info["file_name"], info["sha256"])
    print(f"pyodide {PYODIDE}: runtime + {', '.join(PACKAGES)}")


def make_samples():
    import cv2
    import numpy as np
    from PIL import Image
    from skewcal import analyze as an
    from skewcal.plate import PlateSpec
    import importlib.util
    # in the browser skewcal.py is installed as skewcal_cli.py (the name skewcal is the package)
    spec_ = importlib.util.spec_from_file_location("skewcal_cli", os.path.join(ROOT, "skewcal.py"))
    sys.modules["skewcal_cli"] = importlib.util.module_from_spec(spec_)
    spec_.loader.exec_module(sys.modules["skewcal_cli"])
    import bridge

    out = os.path.join(WEB, "samples")
    os.makedirs(out, exist_ok=True)
    spec = PlateSpec()
    index = []
    for key, title, srcs in SAMPLES:
        names = []
        for k, src in enumerate(srcs):
            g, info, _ = an.load_gray(os.path.join(ROOT, "runs", src))
            dpi = float(info["dpi"][0])
            f = SAMPLE_DPI / dpi
            g = cv2.resize(g, None, fx=f, fy=f, interpolation=cv2.INTER_AREA)
            # crop to the plate plus a white border; the scan's page area is not needed
            dark = g < 0.35
            ys, xs = np.nonzero(cv2.erode(dark.astype(np.uint8), np.ones((9, 9), np.uint8)))
            pad = int(10 / 25.4 * SAMPLE_DPI)
            y0, y1 = max(ys.min() - pad, 0), min(ys.max() + pad, g.shape[0])
            x0, x1 = max(xs.min() - pad, 0), min(xs.max() + pad, g.shape[1])
            g8 = np.clip(g[y0:y1, x0:x1] * 255 + 0.5, 0, 255).astype(np.uint8)
            name = f"{key}_{k + 1}.jpg"
            Image.fromarray(g8).save(os.path.join(out, name), quality=92, dpi=(SAMPLE_DPI, SAMPLE_DPI))
            names.append(name)
        index.append(dict(key=key, title=title, mode="scan", plate="standard", files=names))
        print(f"sample {key}: {names}")
    with open(os.path.join(out, "index.json"), "w") as f:
        json.dump(index, f, indent=1)

    # Precompute the first sample so the page opens on a real result
    first = index[0]
    bridge.reset()
    for name in first["files"]:
        bridge.analyze_one("scan", os.path.join(out, name), name, json.dumps({"plate": first["plate"]}),
                           overlay_dir=out)
    res = json.loads(bridge.combine_all("scan", "{}"))
    res["sample"] = dict(key=first["key"], title=first["title"])
    for im in res["images"]:
        im["overlay"] = "samples/" + os.path.basename(im.pop("overlay_path"))
    with open(os.path.join(WEB, "sample_result.json"), "w") as f:
        json.dump(res, f)
    print(f"sample_result.json: XY angle {res['combined']['theta']:.4f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-samples", action="store_true")
    ap.add_argument("--no-pyodide", action="store_true")
    ap.add_argument("--site", metavar="DIR", help="write a static site (no Pyodide copy, no sample rebuild)")
    a = ap.parse_args()
    bundle_python()
    copy_assets()
    if a.site:
        write_site(a.site)
        return
    export_screen_markers()
    if not a.no_pyodide:
        fetch_pyodide()
    if not a.no_samples:
        make_samples()


if __name__ == "__main__":
    main()
